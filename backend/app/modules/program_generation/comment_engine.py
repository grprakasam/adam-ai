"""
Comment Engine - Adds comments based on verbosity level
"""

from datetime import datetime
from typing import Dict


class CommentEngine:
    """Generates comments at different verbosity levels"""

    @staticmethod
    def generate_header(dataset: str, language: str, verbosity: str, metadata: Dict) -> str:
        """
        Generate file header comment

        Args:
            dataset: ADAM dataset name (e.g., "ADSL")
            language: "R" or "SAS"
            verbosity: "low", "medium", or "high"
            metadata: Dictionary with generation metadata

        Returns:
            Header comment string
        """
        if verbosity == "low":
            if language == "R":
                return f"# {dataset} Generation Code\n# Generated: {datetime.now().strftime('%Y-%m-%d')}\n\n"
            else:
                return f"/* {dataset} Generation Code - Generated: {datetime.now().strftime('%Y-%m-%d')} */\n\n"

        elif verbosity == "medium":
            if language == "R":
                return f"""################################################################################
# PROGRAM: {dataset}.R
# PURPOSE: Generate {dataset} (Subject-Level Analysis Dataset)
# GENERATED: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} UTC
# CDISC VERSION: ADaM IG v{metadata.get('adam_version', '1.3')}
################################################################################

"""
            else:
                return f"""/******************************************************************************
* PROGRAM: {dataset}.sas
* PURPOSE: Generate {dataset} (Subject-Level Analysis Dataset)
* GENERATED: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} UTC
* CDISC VERSION: ADaM IG v{metadata.get('adam_version', '1.3')}
******************************************************************************/

"""

        else:  # high
            study_id = metadata.get('study_id', 'STUDY001')
            sponsor = metadata.get('sponsor', 'Sponsor Name')

            if language == "R":
                return f"""################################################################################
# PROGRAM: {dataset}.R
# PURPOSE: Generate {dataset} (Subject-Level Analysis Dataset)
#
# STUDY: {study_id}
# SPONSOR: {sponsor}
# GENERATED: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} UTC
# GENERATED BY: ADAM AI v2.0
#
# CDISC STANDARDS:
#   - ADaM IG v{metadata.get('adam_version', '1.3')}
#   - SDTM v{metadata.get('sdtm_version', '1.7')}
#
# DESCRIPTION:
#   This program creates the {dataset} dataset following CDISC ADaM standards.
#   All derivations are based on approved specifications and validation rules.
#
# INPUTS:
#   - SDTM datasets (DM, EX, AE, etc.)
#   - Specification: {metadata.get('specification_file', 'Not specified')}
#
# OUTPUTS:
#   - {dataset} dataset in ADaM format
#
################################################################################

"""
            else:
                return f"""/******************************************************************************
* PROGRAM: {dataset}.sas
* PURPOSE: Generate {dataset} (Subject-Level Analysis Dataset)
*
* STUDY: {study_id}
* SPONSOR: {sponsor}
* GENERATED: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} UTC
* GENERATED BY: ADAM AI v2.0
*
* CDISC STANDARDS:
*   - ADaM IG v{metadata.get('adam_version', '1.3')}
*   - SDTM v{metadata.get('sdtm_version', '1.7')}
*
* DESCRIPTION:
*   This program creates the {dataset} dataset following CDISC ADaM standards.
*   All derivations are based on approved specifications and validation rules.
*
* INPUTS:
*   - SDTM datasets (DM, EX, AE, etc.)
*   - Specification: {metadata.get('specification_file', 'Not specified')}
*
* OUTPUTS:
*   - {dataset} dataset in ADaM format
*
******************************************************************************/

"""

    @staticmethod
    def generate_section_comment(category: str, language: str, verbosity: str) -> str:
        """
        Generate section/category comment

        Args:
            category: Category name (e.g., "Demographics")
            language: "R" or "SAS"
            verbosity: "low", "medium", or "high"

        Returns:
            Section comment string
        """
        if verbosity == "low":
            if language == "R":
                return f"## {category}\n"
            else:
                return f"    /* {category} */\n"

        elif verbosity == "medium":
            if language == "R":
                separator = f"# {'-' * 70}\n"
                return f"{separator}# {category.upper()}\n{separator}\n"
            else:
                separator = f"    /* {'-' * 66} */\n"
                return f"{separator}    /* {category.upper()} */\n{separator}\n"

        else:  # high
            description = CommentEngine._get_category_description(category)

            if language == "R":
                separator = f"# {'-' * 70}\n"
                return f"""{separator}# {category.upper()}
# {description}
{separator}
"""
            else:
                separator = f"    /* {'-' * 66} */\n"
                return f"""{separator}    /* {category.upper()}
    /* {description}
{separator}
"""

    @staticmethod
    def _get_category_description(category: str) -> str:
        """Get description for a category"""
        descriptions = {
            "Subject & Study Identifiers": "Unique identifiers for subjects and study",
            "Treatment Variables": "Treatment assignment and randomization variables",
            "Demographics": "Demographic characteristics (age, sex, race, etc.)",
            "Baseline Characteristics": "Baseline values and characteristics",
            "Study Dates": "Important study milestone dates",
            "Disposition Variables": "Subject disposition and completion status",
            "Population Flags": "Analysis population flags (SAFFL, ITTFL, etc.)",
            "Derived Variables": "Calculated and derived analysis variables",
        }
        return descriptions.get(category, "Additional variables for analysis")

    @staticmethod
    def generate_variable_comment(var_name: str, derivation: str, language: str, verbosity: str) -> str:
        """
        Generate inline variable comment

        Args:
            var_name: Variable name
            derivation: Derivation logic description
            language: "R" or "SAS"
            verbosity: "low", "medium", or "high"

        Returns:
            Variable comment string
        """
        if verbosity == "low":
            return ""  # No inline comments for low verbosity

        elif verbosity == "medium":
            if not derivation:
                return ""

            if language == "R":
                return f"# {var_name}: {derivation}\n"
            else:
                return f"    /* {var_name}: {derivation} */\n"

        else:  # high
            if not derivation:
                return ""

            if language == "R":
                return f"""# {var_name}:
#   Derivation: {derivation}
#   Standard: CDISC ADaM IG
"""
            else:
                return f"""    /* {var_name}:
    /*   Derivation: {derivation}
    /*   Standard: CDISC ADaM IG
    */
"""

    @staticmethod
    def generate_footer(language: str, verbosity: str) -> str:
        """Generate file footer comment"""
        if verbosity == "low":
            return "\n"

        elif verbosity in ["medium", "high"]:
            if language == "R":
                return f"""
################################################################################
# END OF PROGRAM
# Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} UTC
################################################################################
"""
            else:
                return f"""
/******************************************************************************
* END OF PROGRAM
* Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} UTC
******************************************************************************/
"""
        return ""
