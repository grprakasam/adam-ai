"""
Code Assembler - Category-based code assembly following CDISC ADAM standards
"""

from typing import List, Dict
from collections import defaultdict
from loguru import logger

from .models import ApprovedVariable


class CodeAssembler:
    """Assembles code snippets in correct CDISC category order"""

    # CDISC ADAM standard category order
    CATEGORY_ORDER = [
        "Subject & Study Identifiers",
        "Treatment Variables",
        "Demographics",
        "Baseline Characteristics",
        "Study Dates",
        "Disposition Variables",
        "Population Flags",
        "Derived Variables",
        "Other",
    ]

    @staticmethod
    def group_by_category(variables: List[ApprovedVariable]) -> Dict[str, List[ApprovedVariable]]:
        """
        Group variables by their category

        Returns:
            Dictionary mapping category name to list of variables
        """
        grouped = defaultdict(list)

        for var in variables:
            category = var.category or "Other"
            grouped[category].append(var)

        logger.info(f"Grouped {len(variables)} variables into {len(grouped)} categories")
        return dict(grouped)

    @staticmethod
    def sort_by_category_order(grouped_variables: Dict[str, List[ApprovedVariable]]) -> List[tuple]:
        """
        Sort categories according to CDISC ADAM standards

        Returns:
            List of (category_name, variables) tuples in correct order
        """
        sorted_categories = []

        # First, add categories in defined order
        for category in CodeAssembler.CATEGORY_ORDER:
            if category in grouped_variables:
                sorted_categories.append((category, grouped_variables[category]))

        # Then, add any additional categories not in the standard list
        for category, variables in grouped_variables.items():
            if category not in CodeAssembler.CATEGORY_ORDER:
                logger.warning(f"Non-standard category found: {category}")
                sorted_categories.append((category, variables))

        return sorted_categories

    @staticmethod
    def assemble_r_code(sorted_categories: List[tuple], comment_verbosity: str, user_preferences: dict) -> str:
        """
        Assemble R code from sorted categories

        Args:
            sorted_categories: List of (category_name, variables) tuples
            comment_verbosity: "low", "medium", or "high"
            user_preferences: User preferences dict

        Returns:
            Complete R code as string
        """
        code_parts = []

        # Header
        if comment_verbosity in ["medium", "high"]:
            header = """################################################################################
# ADAM Dataset Generation Code
# Generated by ADAM AI
# Language: R
################################################################################

"""
            code_parts.append(header)

        # Add library loading
        if user_preferences.get("include_validation", True):
            packages = user_preferences.get("r_packages", ["dplyr", "tidyr", "haven"])
            code_parts.append("# Load required packages\n")
            for pkg in packages:
                code_parts.append(f"library({pkg})\n")
            code_parts.append("\n")

        # Process each category
        for category, variables in sorted_categories:
            if comment_verbosity in ["medium", "high"]:
                separator = f"# {'-' * 70}\n"
                code_parts.append(separator)
                code_parts.append(f"# {category.upper()}\n")
                code_parts.append(separator)
                code_parts.append("\n")
            elif comment_verbosity == "low":
                code_parts.append(f"## {category}\n")

            # Add variable code snippets
            for var in variables:
                if comment_verbosity == "high" and var.derivation_logic:
                    code_parts.append(f"# {var.name}: {var.derivation_logic}\n")

                # Add the actual code
                code_parts.append(var.code_snippet.strip() + "\n")

                # Add user notes if present
                if var.user_notes and comment_verbosity in ["medium", "high"]:
                    code_parts.append(f"# Note: {var.user_notes}\n")

                code_parts.append("\n")

        # Footer with validation
        if user_preferences.get("include_validation", True) and comment_verbosity in ["medium", "high"]:
            code_parts.append("""
# Validation
cat("ADAM dataset generation completed successfully\\n")
cat("Total variables created:", length(names(data)), "\\n")
""")

        return "".join(code_parts)

    @staticmethod
    def assemble_sas_code(sorted_categories: List[tuple], comment_verbosity: str, user_preferences: dict) -> str:
        """
        Assemble SAS code from sorted categories

        Args:
            sorted_categories: List of (category_name, variables) tuples
            comment_verbosity: "low", "medium", or "high"
            user_preferences: User preferences dict

        Returns:
            Complete SAS code as string
        """
        code_parts = []

        # Header
        if comment_verbosity in ["medium", "high"]:
            header = """/******************************************************************************
* ADAM Dataset Generation Code
* Generated by ADAM AI
* Language: SAS
******************************************************************************/

"""
            code_parts.append(header)

        # Add DATA step header
        code_parts.append("DATA adam.dataset;\n")
        code_parts.append("    SET sdtm.dataset;\n\n")

        # Process each category
        for category, variables in sorted_categories:
            if comment_verbosity in ["medium", "high"]:
                separator = f"    /* {'-' * 66} */\n"
                code_parts.append(separator)
                code_parts.append(f"    /* {category.upper()} */\n")
                code_parts.append(separator)
                code_parts.append("\n")
            elif comment_verbosity == "low":
                code_parts.append(f"    /* {category} */\n")

            # Add variable code snippets
            for var in variables:
                if comment_verbosity == "high" and var.derivation_logic:
                    code_parts.append(f"    /* {var.name}: {var.derivation_logic} */\n")

                # Add the actual code (indent for DATA step)
                snippet_lines = var.code_snippet.strip().split('\n')
                for line in snippet_lines:
                    if line.strip():
                        code_parts.append(f"    {line}\n")

                # Add user notes if present
                if var.user_notes and comment_verbosity in ["medium", "high"]:
                    code_parts.append(f"    /* Note: {var.user_notes} */\n")

                code_parts.append("\n")

        # Close DATA step
        code_parts.append("RUN;\n")

        # Footer with validation
        if user_preferences.get("include_validation", True) and comment_verbosity in ["medium", "high"]:
            code_parts.append("""
/* Validation */
PROC CONTENTS DATA=adam.dataset NOPRINT;
RUN;

%PUT ADAM dataset generation completed successfully;
""")

        return "".join(code_parts)

    @staticmethod
    def assemble(variables: List[ApprovedVariable], language: str, comment_verbosity: str, user_preferences: dict) -> str:
        """
        Main assembly method - orchestrates the entire assembly process

        Args:
            variables: List of approved variables
            language: "R" or "SAS"
            comment_verbosity: "low", "medium", or "high"
            user_preferences: User preferences dict

        Returns:
            Complete assembled code
        """
        logger.info(f"Assembling {language} code for {len(variables)} variables")

        # Group by category
        grouped = CodeAssembler.group_by_category(variables)

        # Sort by CDISC order
        sorted_categories = CodeAssembler.sort_by_category_order(grouped)

        # Assemble code based on language
        if language == "R":
            code = CodeAssembler.assemble_r_code(sorted_categories, comment_verbosity, user_preferences)
        elif language == "SAS":
            code = CodeAssembler.assemble_sas_code(sorted_categories, comment_verbosity, user_preferences)
        else:
            raise ValueError(f"Unsupported language: {language}")

        logger.info(f"Code assembly completed: {len(code)} characters")
        return code
